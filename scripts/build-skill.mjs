import { build } from "esbuild";
import { zipSync } from "fflate";
import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const skill = path.join(root, "skills/auditai-seo");
const generated = path.join(skill, "scripts");
await mkdir(generated, { recursive: true });

const [cli, extractor] = await Promise.all([
  build({
    absWorkingDir: root,
    entryPoints: ["scripts/skill/audit-snapshot.ts"],
    bundle: true, write: false, platform: "node", format: "esm", target: "node20",
    // Source stays reviewable in scripts/skill and src/shared/seo; ship one small file.
    minify: true, legalComments: "none",
    banner: { js: "// Generated by npm run build:skill from Pip's shared audit rules. Do not edit." },
  }),
  build({
    absWorkingDir: root,
    entryPoints: ["scripts/skill/capture-page.ts"],
    bundle: true, write: false, platform: "browser", format: "iife", globalName: "AuditAICapture", target: "es2020",
    minifyWhitespace: true, minifySyntax: true, legalComments: "none",
  }),
]);

const cliText = cli.outputFiles[0].text;
const captureText = `// Generated from Pip's read-only DOM extractor with completeness guards.\n(() => {${extractor.outputFiles[0].text}\nreturn AuditAICapture.capturePage();})()\n`;
const generatedFiles = {
  "audit-snapshot.mjs": cliText,
  "capture-page.js": captureText,
};
for (const [name, text] of Object.entries(generatedFiles)) {
  if (Buffer.byteLength(text) > 20 * 1024)
    throw new Error(`${name} exceeds the 20 KiB script review budget.`);
  await writeFile(path.join(generated, name), text);
}

// Explicit allowlist: never package the repository, user files, dependencies, or env.
const resources = [
  "SKILL.md", "agents/openai.yaml", "references/collection.md",
  "references/audit-rubric.md", "references/reporting.md",
  "scripts/audit-snapshot.mjs", "scripts/capture-page.js",
];
const actual = [];
async function list(directory, prefix = "") {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const name = `${prefix}${entry.name}`;
    if (entry.isSymbolicLink()) throw new Error(`Symlinks cannot be packaged: ${name}`);
    if (entry.isDirectory()) await list(path.join(directory, entry.name), `${name}/`);
    else actual.push(name);
  }
}
await list(skill);
if (JSON.stringify(actual.sort()) !== JSON.stringify([...resources].sort()))
  throw new Error("Skill contents differ from the package allowlist. Review before packaging.");
const files = {};
const manifest = [];
for (const resource of [...resources].sort()) {
  const bytes = await readFile(path.join(skill, resource));
  // ZIP stores local calendar fields; fix those fields rather than a UTC instant.
  files[resource] = [new Uint8Array(bytes), { mtime: new Date(2026, 0, 1, 0, 0, 0) }];
  manifest.push({ path: resource, bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") });
}
const archive = zipSync(files, { level: 9 });
const sha256 = createHash("sha256").update(archive).digest("hex");
const artifacts = path.join(root, "artifacts");
await mkdir(artifacts, { recursive: true });
await writeFile(path.join(artifacts, "auditai-seo.zip"), archive);
await writeFile(path.join(artifacts, "auditai-seo.sha256"), `${sha256}  auditai-seo.zip\n`);
await writeFile(path.join(artifacts, "auditai-seo-build.json"), `${JSON.stringify({ name: "auditai-seo", version: "1.0.0", sha256, files: manifest }, null, 2)}\n`);
console.log(`Built auditai-seo: ${resources.length} files, ${archive.length} ZIP bytes. SHA-256 ${sha256}`);
